import express from 'express';
import cors from 'cors';
import { z } from 'zod';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { scoreReview, type Issue, type Review } from './scoring.js';
const here=dirname(fileURLToPath(import.meta.url));
const root=resolve(here,'../../');
const ground=JSON.parse(readFileSync(resolve(root,'benchmarks/ground-truth.json'),'utf8')) as {pullRequest:string;title:string;verifiedIssues:Issue[]};
const sample=JSON.parse(readFileSync(resolve(root,'benchmarks/sample-reviews.json'),'utf8')) as {reviews:Review[]};
const findingSchema=z.object({id:z.string().trim().min(1),category:z.string().trim().min(1),description:z.string().trim().min(1),matchesGroundTruthId:z.string().trim().min(1).nullable()});
const reviewSchema=z.object({reviewer:z.string().trim().min(1),findings:z.array(findingSchema).max(1000)});
export const app=express();
app.use(cors());app.use(express.json({limit:'1mb'}));
app.get('/api/health',(_req,res)=>res.json({ok:true}));
app.get('/api/benchmark',(_req,res)=>res.json({pullRequest:ground.pullRequest,title:ground.title,verifiedIssues:ground.verifiedIssues,synthetic:true,results:sample.reviews.map(r=>scoreReview(ground.verifiedIssues,r))}));
app.post('/api/score',(req,res)=>{const parsed=reviewSchema.safeParse(req.body);if(!parsed.success){res.status(400).json({error:'Invalid review payload',details:parsed.error.flatten()});return;}res.json(scoreReview(ground.verifiedIssues,parsed.data));});
app.use((err:unknown,_req:express.Request,res:express.Response,_next:express.NextFunction)=>{if(err instanceof SyntaxError){res.status(400).json({error:'Invalid JSON payload'});return;}res.status(500).json({error:'Internal server error'});});
